# --------or--------
# True or false --> True
# False or True --> True
# True or 10 == 9 --> True
# False or "gio" == "gio" --> True
# 5 > 3 or 10 >= 10  --> True


# -------and-------
# False and False --> False
# True and True --> True
# 10 == 10 and True --> True
# 5 >= 3 and "nika" == "goga" --> False
# "nika" == "saba" and 10 <= 24 --> False