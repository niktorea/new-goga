# 3)მომხმარებელს შეაყვანინე გამოცდის ქულა 0-დან 100-მდე.
# - 90-100 ქულა — "შესანიშნავი"
# - 70-89 ქულა — "კარგი"
# - 50-69 ქულა — "დამაკმაყოფილებელი"
# - 50-ზე ნაკლები — "ჩაიჭერი"
# დამატებით: თუ მომხმარებელმა 0-ზე ნაკლები ან 100-ზე მეტი ქულა შეიყვანა, გამოიტანე "არასწორი ქულა".

bot = int(input("enter a number 0-100:"))

if bot >= 90 and bot < 100  :
    print("შესანიშნავი")
elif bot >= 70 and bot <= 89  :
    print("კარგი")
elif bot >= 50 and bot <= 69:
    print("დამაკმაყოფილებელი")
elif bot < 50 :
    print("ჩაიჭერი")
else : 
    print("არასწორი ქულა")
