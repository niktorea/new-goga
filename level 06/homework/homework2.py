# - თუ ასაკი 13-ზე ნაკლებია, გამოიტანე "ბავშვი ხარ".
# - თუ ასაკი 13-დან 17-ის ჩათვლითაა, გამოიტანე "მოზარდი ხარ".
# - სხვა შემთხვევაში გამოიტანე "ზრდასრული ხარ".
bot = int(input("enter a age"))
if bot < 13 :
    print("ბავშვი")
elif bot >= 13 and bot <= 17 :
    print("მოზარდი")
else :
    print("ზრდასრული")
